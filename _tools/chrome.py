GA_OLD = re.compile(r'<!--[^\n]*ANALYTICS[^\n]*-->\s*<script async src="https://www\.googletagmanager\.com/gtag/js\?id=G-[A-Z0-9]+"></script>\s*<script>\s*window\.dataLayer[\s\S]*?</script>')
GA_OLD2 = re.compile(r'<script async src="https://www\.googletagmanager\.com/gtag/js\?id=G-[A-Z0-9]+"></script>\s*<script>\s*window\.dataLayer[\s\S]*?</script>')
GA_NEW = re.compile(r'<!-- ── ANALYTICS · Google Analytics 4, loaded only after consent \(udw-ga\) ── -->\s*<script id="udw-ga">[\s\S]*?</script>')

def process(fp, path):
    s = fp.read_text()
    # analytics
    if GA_NEW.search(s): s = GA_NEW.sub(lambda m: GA, s, 1)
    elif GA_OLD.search(s): s = GA_OLD.sub(lambda m: GA, s, 1)
    elif GA_OLD2.search(s): s = GA_OLD2.sub(lambda m: GA, s, 1)
    else: print("  no GA snippet found", fp)
    # css
    s = re.sub(r'<style id="udw-chrome">[\s\S]*?</style>\s*', '', s)
    s = s.replace('</head>', CSS + '\n</head>', 1)
    # header: first <header ...>...</header>
    m = re.search(r'<header\b[^>]*>[\s\S]*?</header>', s)
    status = ''
    if m:
        old = m.group(0)
        if 'id="header-right"' in old:
            st = re.search(r'<div class="header-right" id="header-right">([\s\S]*?)</div>', old)
            status = '<div class="udw-status" id="header-right">%s</div>' % (st.group(1) if st else '')
        s = s[:m.start()] + header(path, status) + s[m.end():]
    else:
        print("  no header", fp)
    # footer: last <footer ...>...</footer>
    ms = list(re.finditer(r'<footer\b[^>]*>[\s\S]*?</footer>', s))
    if ms:
        m = ms[-1]; old = m.group(0)
        if 'class="udw-f"' in old:
            nm = re.search(r'<div class="udw-f-note">([\s\S]*?)</div>\n    <nav class="udw-f-nav"', old)
            note = nm.group(1) if nm else ''
        else:
            inner = re.sub(r'^<footer\b[^>]*>|</footer>$', '', old).strip()
            inner = re.sub(r'^<div class="wrap">([\s\S]*)</div>$', r'\1', inner).strip()
            note = inner
        s = s[:m.start()] + footer(note) + s[m.end():]
    else:
        print("  no footer", fp)
    # consent
    s = re.sub(r'<!-- udw-consent -->[\s\S]*?<!-- /udw-consent -->\s*', '', s)
    idx = s.rfind('</body>')
    s = s[:idx] + CONSENT + '\n' + s[idx:]
    fp.write_text(s)

if __name__ == '__main__':
    root = pathlib.Path('.')
    for fp in sorted(root.rglob('*.html')):
        if '.git' in fp.parts or fp.name.startswith('google'): continue
        rel = '/' + str(fp.parent).strip('.').strip('/')
        path = '/' if rel == '/' else rel + '/'
        if fp.name == '404.html': path = '/404'
        print(fp, path)
        process(fp, path)
