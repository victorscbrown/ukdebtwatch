def nav_links(path, cls_current=True):
    out = []
    for href, label in NAV:
        cur = (href == path) or (href == "/articles/" and path in ARTICLE_PATHS)
        out.append('<a href="%s"%s>%s</a>' % (href, ' aria-current="page"' if cur else '', label))
    return "".join(out)

